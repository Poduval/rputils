
#' Set up, build and check an \code{smr} model package.
#'
#' @description  
#' These functions are designed for building model packages in the smr setup.
#' The most important features of these packages are that they contain several model releases 
#' saved as separate environment objects in R and that no objects are exported from their namespace.
#' 
#' For non-model packages, it's more convenient to work with \code{devtools}.
#' 
#' @param name,path,list,force,...  As in \code{utils::\link{package.skeleton}}. 
#' The dots in \code{pkg.check} are passed to \code{devtools::\link{check_built}}, 
#' those in \code{pkg.binary} are passed to \code{devtools::\link{build}}.
#' @param description A list of entries to add to the package description file. 
#' Default is the description created by \code{utils::\link{package.skeleton}}
#' @param namespace A character vector containing code lines to include in the namespace file.
#' @param sysdata A character vector: Names of objects in the global environment 
#' to be added to \code{sysdata.rda} 
#' (see \url{http://r-pkgs.had.co.nz/data.html#data-sysdata} - note however that our implementation$
#' does not use the package \code{usethis}). 
#' \code{sysdata} will usually include the model release environments.
#' @param save.version Passed to \code{\link{save}} as its \code{version} argument.
#' \code{version=2} is default under R 3.4.4, \code{version=3} under R 3.5.0 and newer.
#' \code{*.Rdata} files written using \code{version=3} can not be read by R 3.4.4.
#' @param args Options to be appended to \code{R CMD build}.
#' 
#' @name pkgfuns
#'
#' @details 
#' Two object classes are used: 
#' \code{"pkg.source"}, containing the path to the home directory of the package's sources and
#' \code{"pkg.built"} containing the path and file name of a bundled package file (\code{*.tar.gz}).
#' 
#' A \code{"pkg.source"} object is created with \code{pkg.setup()} (internally using 
#' \code{utils::\link{package.skeleton}}) and can be transformed into a \code{"pkg.built"} object 
#' with \code{pkg.build()} (executing \code{R CMD build} behind the scenes).
#' A \code{"pkg.built"} object can be checked by applying \code{pkg.check()} 
#' (\code{R CMD check}), or transformed into a compiled \code{.zip} file by \code{pkg.binary()}
#' (\code{R CMD INSTALL} with option \code{--build}).
NULL


#' @describeIn pkgfuns
#' Set up a smr model package. Uses \code{utils::\link{package.skeleton}}.
#' 
#' @importFrom utils package.skeleton
#' @export
pkg.setup <- function(name, path, list,
                      description = NULL, namespace = NULL, sysdata = NULL,
                      save.version = 2, force = TRUE, ...){

  path <- normalizePath(path, "/")
  oldwd <- setwd(path)
  on.exit(setwd(oldwd))

  # unlink(file.path(path, name), recursive = TRUE)
  suppressMessages(package.skeleton(name = name, list = list, path = path, force = force, ...))

  if (!is.null(sysdata)){
    tmp <- tempfile(fileext = ".RData")
    save(list = sysdata, file = tmp, version = save.version, compress = FALSE)
    file.copy(tmp, file.path(path, name, "R", "sysdata.rda"), overwrite = TRUE, copy.date = TRUE)
  }

  stopifnot(file.exists(file.path(path, name, c("DESCRIPTION", "NAMESPACE"))))

  # Description
  descript <- modifyDescriptionFile(name = name, path = path, description = description)
  
  # Remove man and "Read-and-delete-me"
  unlink(file.path(path, name, "man"), recursive = TRUE)
  unlink(file.path(path, name, "Read-and-delete-me"))

  # Namespace: remove everything
  write(namespace, file = file.path(path, name, "NAMESPACE"), append = FALSE)

  # Copy 'release_notes' file if it exists
  releaseNotes <- file.path(oldwd, "4_Implementation/01_release_notes.md")
  if (file.exists(releaseNotes)){
    if (!dir.exists(file.path(name, "inst"))) 
      dir.create(file.path(name, "inst"))
    stopifnot(file.copy(releaseNotes, file.path(name, "inst/NEWS"),
                        overwrite = TRUE))
  }
  
  structure(file.path(path, name), class = "pkg.source",
            description = descript, path = path)
}

# modifyDescriptionFile
# Modify an existing description file
# (this functino is used in pkg.setup to adjust the description file generated by package.skeleton
#  according to the description argument)
# Arguments: 
#   name, path, list, force, ...  As in utils::package.skeleton
#   description                   A list of entries to add/modify in the package description 
#                                 generated by default in utils::package.skeleton
#' @importFrom utils write.table
modifyDescriptionFile <- function(name, path, description = NULL){
  
  descFiles <- file.path(path, name, "DESCRIPTION")
  
  # ---- lines copied from 'Packaging functions.R' ----
  descript <- readLines(descFiles)
  descript <- structure(sub("^[^\\:]+\\:[ ]*(.*)$", "\\1", descript),
                        names = sub("^([^\\:]+)\\:.*$", "\\1", descript))
  descript <- as.list(descript)
  descript[names(description)] <- description
  
  write.table(paste0(names(descript), ": ", descript),
              sep = "\n", quote = FALSE, row.names = FALSE, col.names = FALSE,
              file = descFiles,
              append = FALSE)
  # ---- end of lines copied from 'Packaging functions.R' ----
  
  message("File \"", descFiles, "\" was modified.")
  descript
}

#' @export
print.pkg.source <- function(x, ...){
  cat("--- Source of an R package ---\n")
  desc <- attr(x, "description")
  do.call(cat, c(paste0(format(paste0(names(desc), ": ")), unlist(desc)), list(sep = "\n")))
  cat("(Stored in: \"", attr(x, "path"), "\")\n", sep = "")
  invisible(desc$Package)
}

#' @describeIn pkgfuns
#' Takes an object of class \code{pkg.setup} and 
#' executes \code{R CMD build}, i.e. builds a tar file (\code{*.tar.gz}).
#' Returns a character string of class \code{pkg.built}, the path and name of the tar file.
#'
#' @param x Object of an appropriate class (depending on the function - see section \dQuote{Functions} below). 
#'
#' @export
pkg.build <- function(x, args = ""){
  stopifnot(inherits(x, "pkg.source"))
  oldwd <- setwd(attr(x, "path"))
  on.exit(setwd(oldwd))
  desc <- attr(x, "description")
  shell(paste0("R CMD build ", desc$Package, args)) # " --resave-data"))
  built.name <- paste0(desc$Package, "_", desc$Version, ".tar.gz")
  if (dir.exists(file.path(project.home, "../model.serviceR.general/.git/"))){
    writeLines(c(
        "=== State of model.serviceR.general at production: ===",
        readLines(file.path(project.home, "../model.serviceR.general/.git/HEAD")),
        readLines(file.path(project.home, "../model.serviceR.general/.git/FETCH_HEAD"))),
      con = file.path(attr(x, "path"), "Status_model.serviceR.general.txt"))
  }
  invisible(structure(file.path(attr(x, "path"), built.name), class = "pkg.built",
                      description = desc, path = attr(x, "path")))
}

#' @export
print.pkg.built <- function(x, ...){
  cat("--- Built R package ---\n")
  desc <- attr(x, "description")
  do.call(cat, c(paste0(format(paste0(names(desc), ": ")), unlist(desc)), list(sep = "\n")))
  cat("(File: \"", x, "\")\n", sep = "")
  invisible(desc$Package)
}

#' @describeIn pkgfuns
#' Takes an object of class \code{pkg.built} (as created by \code{pkg.build}) and 
#' executes \code{R CMD check} using \code{devtools::\link{check_built}}. 
#' The \dots are passed to \code{devtools::check_built}.
#'
#' @param check_dir,manual,env_var Passed to \code{check_built}.
#' @param options Defunct - don't use this parameter!
#'
#' @importFrom devtools check_built
#' @export
pkg.check <- function(x, 
  check_dir = if (setup.ok) file.path(project.home, "5_Release", model.release) else tempdir(), 
  manual = FALSE, env_var = c(R_LIBS_USER = .libPaths()), ..., options){
  stopifnot(inherits(x, "pkg.built"))
  setup.ok <- all(sapply(c("project.home", "model.release"), exists, envir = parent.frame(), inherits = FALSE)) && 
                dir.exists(file.path(project.home, "5_Release", model.release))
  if (!missing(options)){
    warning("The parameter 'options' is defunct and will be ignored - remove it from the code!")
  }
  out <- devtools::check_built(x,
                               check_dir = check_dir, manual = manual,
                               env_var = env_var, ...)
  invisible(out)
}

#' @describeIn pkgfuns
#' Takes an object of class \code{pkg.built} (as created by \code{pkg.build}) and 
#' builds a windows binary package (\code{*.zip} file)
#' with \code{devtools::\link{build}(x, binary = TRUE, ...)}.
#'  
#' @param install.dir Directory where the \code{*.zip} file is moved to after its generation.
#' 
#' @importFrom devtools build
#' @export
pkg.binary <- function(x, install.dir = attr(x, "path"), ...){
  stopifnot(inherits(x, "pkg.built"))
  oldwd <- setwd(attr(x, "path"))
  on.exit(setwd(oldwd))
  desc <- attr(x, "description")
  devtools::build(desc$Package, binary = TRUE, ...)
  binary.name <- paste0(desc$Package, "_", desc$Version, ".zip")
  stopifnot(file.exists(binary.name))
  if (install.dir != attr(x, "path")){
    stopifnot(file.copy(binary.name, file.path(install.dir, binary.name),
                        copy.date = TRUE, overwrite = TRUE))
    file.remove(binary.name)
  }
  invisible(structure(file.path(install.dir, binary.name), class = "pkg.binary",
                      description = desc, built = as.vector(x)))
}
#' @export
print.pkg.binary <- function(x, ...){
  cat("--- Windows-binary R package ---\n")
  desc <- attr(x, "description")
  do.call(cat, c(paste0(format(paste0(names(desc), ": ")), unlist(desc)), list(sep = "\n")))
  cat("(File: \"", x, "\")\n", sep = "")
  invisible(desc$Package)
}

